-- T32 – DDL mảng A: Nhân viên y tế & Lịch làm việc
-- PostgreSQL 16. Chạy trước B_schema.sql.
-- Mô hình 8A: NHAN_VIEN -> BAC_SI; BAC_SI -> BAC_SI_DA_KHOA / BAC_SI_CHUYEN_KHOA.

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE nhan_vien (
    ma_nv       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ho_ten      VARCHAR(100) NOT NULL CHECK (btrim(ho_ten) <> ''),
    ngay_sinh   DATE NOT NULL CHECK (ngay_sinh <= CURRENT_DATE),
    sdt         VARCHAR(10) NOT NULL UNIQUE CHECK (sdt ~ '^0[0-9]{9}$'),
    email       VARCHAR(100) CHECK (email IS NULL OR email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
    loai_nv     VARCHAR(24) NOT NULL CHECK (loai_nv IN (
                    'BAC_SI', 'LE_TAN', 'QUAN_TRI_NHAN_SU',
                    'QUAN_TRI_TAI_KHOAN', 'QUAN_TRI_DANH_MUC')),
    CONSTRAINT pk_nhan_vien PRIMARY KEY (ma_nv)
);

CREATE TABLE bac_si (
    ma_bac_si       INTEGER,
    so_chung_chi    VARCHAR(30) NOT NULL UNIQUE CHECK (btrim(so_chung_chi) <> ''),
    ngay_cap_cc     DATE NOT NULL,
    ngay_het_han_cc DATE NOT NULL,
    loai_bac_si     VARCHAR(16) NOT NULL CHECK (loai_bac_si IN ('DA_KHOA', 'CHUYEN_KHOA')),
    CONSTRAINT pk_bac_si PRIMARY KEY (ma_bac_si),
    CONSTRAINT fk_bac_si_nhan_vien FOREIGN KEY (ma_bac_si)
        REFERENCES nhan_vien (ma_nv) ON DELETE RESTRICT,
    CONSTRAINT ck_bac_si_han_giay_phep CHECK (ngay_het_han_cc > ngay_cap_cc)
);

CREATE TABLE bac_si_da_khoa (
    ma_bac_si INTEGER,
    CONSTRAINT pk_bac_si_da_khoa PRIMARY KEY (ma_bac_si),
    CONSTRAINT fk_bac_si_da_khoa_bac_si FOREIGN KEY (ma_bac_si)
        REFERENCES bac_si (ma_bac_si) ON DELETE CASCADE
);

CREATE TABLE chuyen_khoa (
    ma_chuyen_khoa INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ten_chuyen_khoa VARCHAR(100) NOT NULL UNIQUE CHECK (btrim(ten_chuyen_khoa) <> ''),
    CONSTRAINT pk_chuyen_khoa PRIMARY KEY (ma_chuyen_khoa)
);

CREATE TABLE bac_si_chuyen_khoa (
    ma_bac_si      INTEGER,
    ma_chuyen_khoa INTEGER NOT NULL,
    CONSTRAINT pk_bac_si_chuyen_khoa PRIMARY KEY (ma_bac_si),
    CONSTRAINT fk_bac_si_chuyen_khoa_bac_si FOREIGN KEY (ma_bac_si)
        REFERENCES bac_si (ma_bac_si) ON DELETE CASCADE,
    CONSTRAINT fk_bac_si_chuyen_khoa_chuyen_khoa FOREIGN KEY (ma_chuyen_khoa)
        REFERENCES chuyen_khoa (ma_chuyen_khoa) ON DELETE RESTRICT
);

CREATE TABLE ca_lam_viec (
    ma_ca        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    thoi_gian_bd TIMESTAMP NOT NULL,
    thoi_gian_kt TIMESTAMP NOT NULL,
    trang_thai   VARCHAR(8) NOT NULL DEFAULT 'DA_XEP' CHECK (trang_thai IN ('DA_XEP', 'HUY')),
    ma_bac_si    INTEGER NOT NULL,
    CONSTRAINT pk_ca_lam_viec PRIMARY KEY (ma_ca),
    CONSTRAINT fk_ca_lam_viec_bac_si FOREIGN KEY (ma_bac_si)
        REFERENCES bac_si (ma_bac_si) ON DELETE RESTRICT,
    CONSTRAINT ck_ca_lam_viec_thoi_gian CHECK (thoi_gian_kt > thoi_gian_bd),
    CONSTRAINT ex_ca_lam_viec_bac_si EXCLUDE USING gist (
        ma_bac_si WITH =,
        tsrange(thoi_gian_bd, thoi_gian_kt, '[)') WITH &&
    ) WHERE (trang_thai = 'DA_XEP')
);

CREATE INDEX idx_ca_lam_viec_bac_si_thoi_gian ON ca_lam_viec (ma_bac_si, thoi_gian_bd);
CREATE INDEX idx_bac_si_chuyen_khoa_chuyen_khoa ON bac_si_chuyen_khoa (ma_chuyen_khoa);
