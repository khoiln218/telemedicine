--   bac_si_da_khoa(ma_bac_si INTEGER PK)  – phân lớp BAC_SI theo 8A,
--   chuyen_khoa(ma_chuyen_khoa INTEGER PK).
-- Giá trị vai_tro trùng giá trị nhan_vien.loai_nv, thêm BENH_NHAN.
--
-- Ràng buộc cần trigger (BR-B01; B03 phần hạn, chuyên khoa, tái khám; B05; B09 phần vai trò;
-- B10 không xóa tài khoản) nằm ở B_trigger_view.sql (T37); phân quyền BR-B08, B10 ở rbac.sql (T45).
-- Không có ON DELETE CASCADE: bệnh nhân, lịch hẹn, tài khoản không bị xóa khi còn tham chiếu.
-- Khóa tự tăng: dữ liệu mẫu (T39) không ghi mã; nếu ghi tường minh thì phải setval sequence,
-- nếu không lần thêm kế tiếp sẽ trùng khóa.

CREATE EXTENSION IF NOT EXISTS btree_gist;  -- cho EXCLUDE trên cột INTEGER (BR-B02)

CREATE TABLE benh_nhan (
    ma_bn       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ho_ten      VARCHAR(100) NOT NULL,
    ngay_sinh   DATE         NOT NULL,
    gioi_tinh   VARCHAR(3)   NOT NULL CHECK (gioi_tinh IN ('NAM', 'NU')),
    sdt         VARCHAR(10)  NOT NULL UNIQUE CHECK (sdt ~ '^0[0-9]{9}$'),
    email       VARCHAR(100)
);

CREATE TABLE giay_chuyen_khoa (
    ma_giay         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ngay_lap        DATE    NOT NULL DEFAULT CURRENT_DATE,
    ly_do           TEXT    NOT NULL,
    ngay_het_han    DATE    NOT NULL,
    ma_bn           INTEGER NOT NULL REFERENCES benh_nhan (ma_bn),
    ma_bac_si_lap   INTEGER NOT NULL REFERENCES bac_si_da_khoa (ma_bac_si),        -- BR-B07: chỉ bác sĩ đa khoa
    ma_chuyen_khoa  INTEGER NOT NULL REFERENCES chuyen_khoa (ma_chuyen_khoa),
    -- BR-B07: hiệu lực tối đa 30 ngày kể từ ngày lập
    CONSTRAINT ck_giay_han CHECK (ngay_het_han > ngay_lap AND ngay_het_han <= ngay_lap + 30),
    -- đích của khóa ngoại kép từ lich_hen (BR-B03: giấy của chính bệnh nhân)
    CONSTRAINT uq_giay_benh_nhan UNIQUE (ma_giay, ma_bn)
);

CREATE TABLE lich_hen (
    ma_lh           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thoi_gian_bd    TIMESTAMP     NOT NULL,
    thoi_gian_kt    TIMESTAMP     NOT NULL,
    ly_do_kham      TEXT          NOT NULL,
    trang_thai      VARCHAR(11)   NOT NULL DEFAULT 'DA_DAT'
                    CHECK (trang_thai IN ('DA_DAT', 'DA_XAC_NHAN', 'HOAN_THANH', 'HUY', 'VANG_MAT')),
    hinh_thuc       VARCHAR(9)    NOT NULL CHECK (hinh_thuc IN ('TRUC_TIEP', 'TU_XA')),
    phi_kham        NUMERIC(12,0) NOT NULL CHECK (phi_kham >= 0),
    ngay_tao        TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP(0),
    phong_kham      VARCHAR(20),
    nen_tang        VARCHAR(30),
    link_phien      VARCHAR(255),
    ma_bn           INTEGER NOT NULL REFERENCES benh_nhan (ma_bn),
    ma_bac_si       INTEGER NOT NULL REFERENCES bac_si (ma_bac_si),
    ma_giay         INTEGER UNIQUE,                                                -- BR-B03: mỗi giấy dùng một lần
    CONSTRAINT ck_lich_hen_thoi_gian CHECK (thoi_gian_kt > thoi_gian_bd),
    -- BR-B04, BR-B06: phân lớp 8C, mỗi hình thức có đúng thông tin của mình
    CONSTRAINT ck_lich_hen_hinh_thuc CHECK (
        (hinh_thuc = 'TRUC_TIEP' AND phong_kham IS NOT NULL AND nen_tang IS NULL AND link_phien IS NULL)
     OR (hinh_thuc = 'TU_XA' AND phong_kham IS NULL AND nen_tang IS NOT NULL AND link_phien IS NOT NULL)
    ),
    -- BR-B03: giấy chuyển phải cấp cho chính bệnh nhân của lịch hẹn
    CONSTRAINT fk_lich_hen_giay FOREIGN KEY (ma_giay, ma_bn)
        REFERENCES giay_chuyen_khoa (ma_giay, ma_bn),
    -- BR-B02: lịch còn hiệu lực của cùng bác sĩ, cùng bệnh nhân không giao nhau;
    -- tsrange mặc định [bd, kt) nên hai lịch nối tiếp không bị tính là giao nhau
    CONSTRAINT ex_lich_hen_bac_si EXCLUDE USING gist (
        ma_bac_si WITH =, tsrange(thoi_gian_bd, thoi_gian_kt) WITH &&
    ) WHERE (trang_thai NOT IN ('HUY', 'VANG_MAT')),
    CONSTRAINT ex_lich_hen_benh_nhan EXCLUDE USING gist (
        ma_bn WITH =, tsrange(thoi_gian_bd, thoi_gian_kt) WITH &&
    ) WHERE (trang_thai NOT IN ('HUY', 'VANG_MAT'))
);

CREATE TABLE tai_khoan (
    ten_dang_nhap   VARCHAR(50)  PRIMARY KEY,
    mat_khau_hash   VARCHAR(255) NOT NULL,
    vai_tro         VARCHAR(18)  NOT NULL CHECK (vai_tro IN (
                        'QUAN_TRI_NHAN_SU', 'QUAN_TRI_TAI_KHOAN', 'QUAN_TRI_DANH_MUC',
                        'BAC_SI', 'LE_TAN', 'BENH_NHAN')),
    trang_thai      VARCHAR(9)   NOT NULL DEFAULT 'HOAT_DONG'
                    CHECK (trang_thai IN ('HOAT_DONG', 'KHOA')),
    ma_bn           INTEGER UNIQUE REFERENCES benh_nhan (ma_bn),                   -- BR-B09: tối đa một tài khoản
    ma_nv           INTEGER UNIQUE REFERENCES nhan_vien (ma_nv),
    -- BR-B09: tài khoản bệnh nhân gắn đúng một bệnh nhân, tài khoản khác gắn đúng một nhân viên
    CONSTRAINT ck_tai_khoan_chu_so_huu CHECK (
        (vai_tro = 'BENH_NHAN' AND ma_bn IS NOT NULL AND ma_nv IS NULL)
     OR (vai_tro <> 'BENH_NHAN' AND ma_bn IS NULL AND ma_nv IS NOT NULL)
    )
);

-- Chỉ mục. PK, UNIQUE, EXCLUDE đã tự tạo chỉ mục; EXCLUDE chỉ phủ lịch còn hiệu lực,
-- nên thêm B-tree cho tra cứu lịch hẹn theo bác sĩ, bệnh nhân, ngày (kể cả lịch đã hủy).
CREATE INDEX idx_lich_hen_bac_si    ON lich_hen (ma_bac_si, thoi_gian_bd);
CREATE INDEX idx_lich_hen_benh_nhan ON lich_hen (ma_bn, thoi_gian_bd);
CREATE INDEX idx_lich_hen_thoi_gian ON lich_hen (thoi_gian_bd);
CREATE INDEX idx_giay_benh_nhan     ON giay_chuyen_khoa (ma_bn);
