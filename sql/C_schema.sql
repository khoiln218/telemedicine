-- Chạy sau A_schema.sql và B_schema.sql (PostgreSQL 16).
-- B phụ thuộc: benh_nhan(ma_bn), lich_hen(ma_lh, ma_bn, ma_bac_si, trang_thai),
--              tai_khoan(ten_dang_nhap, vai_tro, ma_bn, ma_nv).
-- Quy tắc liên bảng và lịch sử nằm ở C_trigger_view.sql (T38); quyền ở rbac.sql (T45).
-- Dùng IDENTITY BY DEFAULT để có thể nạp fixture có mã xác định; seed chuẩn nên bỏ mã.

CREATE TABLE lan_kham (
    ma_lan_kham     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_lh           INTEGER NOT NULL UNIQUE REFERENCES lich_hen (ma_lh),
    thoi_diem_kham  TIMESTAMP NOT NULL,
    tom_tat         TEXT NOT NULL CHECK (btrim(tom_tat) <> ''),
    created_by      VARCHAR(50) NOT NULL REFERENCES tai_khoan (ten_dang_nhap)
);

CREATE TABLE ma_icd10 (
    ma_icd10    VARCHAR(10) PRIMARY KEY,
    mo_ta       VARCHAR(255) NOT NULL CHECK (btrim(mo_ta) <> '')
);

CREATE TABLE chan_doan (
    ma_chan_doan       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_lan_kham        INTEGER NOT NULL REFERENCES lan_kham (ma_lan_kham),
    ma_icd10           VARCHAR(10) NOT NULL REFERENCES ma_icd10 (ma_icd10),
    la_chan_doan_chinh BOOLEAN NOT NULL DEFAULT FALSE,
    ghi_chu            TEXT,
    trang_thai         VARCHAR(8) NOT NULL DEFAULT 'HIEU_LUC'
                       CHECK (trang_thai IN ('HIEU_LUC', 'DA_HUY'))
);

CREATE TABLE don_thuoc (
    ma_don         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_lan_kham    INTEGER NOT NULL REFERENCES lan_kham (ma_lan_kham),
    thoi_diem_ke   TIMESTAMP NOT NULL,
    trang_thai     VARCHAR(8) NOT NULL DEFAULT 'HIEU_LUC'
                   CHECK (trang_thai IN ('HIEU_LUC', 'DA_HUY')),
    created_by     VARCHAR(50) NOT NULL REFERENCES tai_khoan (ten_dang_nhap)
);

CREATE TABLE thuoc (
    ma_thuoc       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten_thuoc      VARCHAR(150) NOT NULL,
    dang_bao_che   VARCHAR(80) NOT NULL,
    ham_luong      VARCHAR(80) NOT NULL
);

CREATE TABLE hoat_chat (
    ma_hoat_chat   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten_hoat_chat  VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE chi_tiet_don_thuoc (
    ma_don       INTEGER NOT NULL REFERENCES don_thuoc (ma_don),
    ma_thuoc     INTEGER NOT NULL REFERENCES thuoc (ma_thuoc),
    so_luong     INTEGER NOT NULL CONSTRAINT ck_chi_tiet_don_thuoc_so_luong CHECK (so_luong > 0),
    lieu_dung    TEXT NOT NULL CHECK (btrim(lieu_dung) <> ''),
    PRIMARY KEY (ma_don, ma_thuoc)
);

CREATE TABLE thuoc_hoat_chat (
    ma_thuoc      INTEGER NOT NULL REFERENCES thuoc (ma_thuoc),
    ma_hoat_chat  INTEGER NOT NULL REFERENCES hoat_chat (ma_hoat_chat),
    ham_luong     VARCHAR(80) NOT NULL CHECK (btrim(ham_luong) <> ''),
    PRIMARY KEY (ma_thuoc, ma_hoat_chat)
);

CREATE TABLE di_ung (
    ma_bn          INTEGER NOT NULL REFERENCES benh_nhan (ma_bn),
    ma_hoat_chat   INTEGER NOT NULL REFERENCES hoat_chat (ma_hoat_chat),
    ngay_ghi_nhan  DATE NOT NULL DEFAULT CURRENT_DATE,
    ghi_chu        TEXT,
    PRIMARY KEY (ma_bn, ma_hoat_chat)
);

-- PK/UNIQUE tạo chỉ mục tương ứng; các chỉ mục dưới đây hỗ trợ tra cứu theo lịch sử.
CREATE INDEX idx_chan_doan_lan_kham ON chan_doan (ma_lan_kham, trang_thai);
CREATE INDEX idx_don_thuoc_lan_kham ON don_thuoc (ma_lan_kham, thoi_diem_ke);
CREATE INDEX idx_don_thuoc_ngay_hieu_luc ON don_thuoc (thoi_diem_ke, ma_don)
    WHERE trang_thai = 'HIEU_LUC';
CREATE INDEX idx_chi_tiet_thuoc ON chi_tiet_don_thuoc (ma_thuoc, ma_don);
CREATE INDEX idx_thuoc_hoat_chat_hc ON thuoc_hoat_chat (ma_hoat_chat, ma_thuoc);
CREATE INDEX idx_di_ung_hoat_chat ON di_ung (ma_hoat_chat, ma_bn);
